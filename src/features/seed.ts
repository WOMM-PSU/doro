const iso = (date: Date) => date.toISOString();

function daysAgo(now: Date, days: number, hour = 12, minute = 0): Date {
  const date = atLocalTime(now, hour, minute);
  date.setDate(date.getDate() - days);
  return date;
}

function hoursAgo(now: Date, hours: number): Date {
  return new Date(now.getTime() - hours * 3_600_000);
}

/** A daytime deadline that is always in the future at seed time. */
function futureAt(now: Date, hour: number, minute = 0, minLeadHours = 2): Date {
  const candidate = atLocalTime(now, hour, minute);
  if (candidate.getTime() - now.getTime() < minLeadHours * 3_600_000) {
    candidate.setDate(candidate.getDate() + 1);
  }
  return candidate;
}

